"""Deterministic re-execution of a recorded Q0 episode's plans on a NativeMujocoBackend.

session/execution.jsonl holds every accepted plan, each executed group's requested targets and per-step motion
joint targets, and the checkpoint decisions. `replay_plans` drives the backend with the unchanged Executor; the
recorded motion targets replace path planning (no IK/planner randomness), everything else (gripper events,
convergence steps, station hooks, recorder) is regenerated by the same code. Used by scripts/replay_q0_episode.py
(videos, audits) and by scripts/run_q0_episode.py --resume-from (continue an episode that was cut off).
"""
import json
from pathlib import Path

import numpy as np

from ..controller.executor import Executor, Replan, Ended
from ..runtime.protocol import ARMS, frame


def load_trace(run):
    return [json.loads(line) for line in (Path(run)/'session/execution.jsonl').read_text().splitlines() if line.strip()]


def load_plans(trace):
    """[(payload, [recorded groups], [checkpoint decisions])] in execution order."""
    plans, cur = [], None
    for e in trace:
        if e['event'] == 'plan':
            cur = {'payload': e['payload'], 'groups': [], 'decisions': [], 'plan_number': e['plan_number']}
            plans.append(cur)
        elif cur is None:
            continue
        elif e['event'] == 'group_started':
            cur['groups'].append({'requested': e['requested'], 'qs': []})
        elif e['event'] == 'control_step' and cur['groups']:
            cur['groups'][-1]['qs'].append(e)
        elif e['event'] == 'checkpoint_decision':
            cur['decisions'].append({'decision': e['decision'], 'reason': e['reason']})
    return plans


def replay_plans(b, trace):
    """Re-execute every recorded plan on backend `b` (stops at Ended). -> report dict.

    Every recorded motion step's actual joints are compared with the replay (`mismatches`: steps differing by more
    than 1e-9 rad)."""
    ex = Executor(b)
    if hasattr(b, 'attach_executor'):
        b.attach_executor(ex)   # recorded compliant groups are re-executed compliantly
    queue, mismatch = [], []

    def prepare(group):
        rec = queue.pop(0) if queue else None
        if rec is None or rec['requested'] != group:
            raise Replan('replay: no recorded execution for this group (planning rejected it originally)')
        active = ARMS if group['active_arms'] == 'both' else (() if group['active_arms'] == 'none' else (group['active_arms'],))
        goals = {x: frame(group[x]) for x in active}
        qs = [{x: np.asarray(s['target_joints'][x], float) for x in ARMS} for s in rec['qs']]
        rec['cursor'] = 0
        ex._replay_rec = rec
        return active, goals, qs

    original_step = b.step

    def checked_step(q, g):
        original_step(q, g)
        rec = getattr(ex, '_replay_rec', None)
        if rec is not None and b.step_phase == 'motion' and rec['cursor'] < len(rec['qs']):
            s = rec['qs'][rec['cursor']]
            if all(np.allclose(q[x], s['target_joints'][x], atol=0, rtol=0) for x in ARMS):
                rec['cursor'] += 1
                err = max(float(np.max(abs(b.data.qpos[b.arm[x]['qids']]-np.asarray(s['actual_joints'][x])))) for x in ARMS)
                if err > 1e-9:
                    mismatch.append({'sim_time_s': s['sim_time_s'], 'max_abs_joint_diff': err})

    b.step = checked_step
    ex._prepare = prepare
    plans = load_plans(trace)
    ended = False
    try:
        for plan in plans:
            queue[:] = list(plan['groups'])
            decisions = list(plan['decisions'])
            try:
                ex.execute(plan['payload'], (lambda *_: decisions.pop(0)) if decisions else None)
            except Ended:
                ended = True
                break
    finally:
        del b.step   # restore the bound method
    return {'plans': len(plans), 'last_plan_number': plans[-1]['plan_number'] if plans else None,
            'groups': sum(len(p['groups']) for p in plans), 'control_steps': b.steps,
            'motion_steps_compared': sum(1 for e in trace if e['event'] == 'control_step'),
            'motion_step_mismatches': len(mismatch), 'first_mismatches': mismatch[:5], 'ended': ended}
